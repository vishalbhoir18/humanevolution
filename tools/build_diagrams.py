#!/usr/bin/env python3
"""Build the lateral skull diagrams for the specimen record.

    python tools/build_diagrams.py            # -> diagrams/skulls.js
    python tools/build_diagrams.py --preview DIR   # also writes DIR/<id>.svg

Needs numpy and shapely.  See tools/diagrams/skulls.py for the landmark data.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np  # noqa: E402

from diagrams import draw  # noqa: E402
from diagrams.skulls import SKULLS  # noqa: E402

REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "diagrams", "skulls.js")
ORDER = ("dryo", "rama", "austra", "habilis", "erectus", "neander", "sapiens")

# Recorded endocranial volumes of the specimens drawn (cc), used only to
# sanity-check the brain-space outlines against each other.
SPECIMEN_CC = dict(dryo=320, rama=None, austra=485, habilis=510, erectus=1004, neander=1625, sapiens=1600)


CHAR_W = 5.55    # advance of one 9.2-unit IBM Plex Mono character (0.6 em)


def label_extent(lab, ax):
    """x range (mm) covered by a label's text."""
    tx, ty = lab["to"]
    w = max(len(t) for t in lab["text"].split("\n")) * CHAR_W
    anchor = lab.get("anchor", "end" if tx > ax else "start")
    # anchor "end": text ends at tx and runs forward (to larger x, i.e. leftward on screen)
    return (tx, tx + w) if anchor == "end" else (tx - w, tx)


def common_viewbox(skulls):
    """One viewBox for all diagrams, so they share a scale (1 unit = 1 mm)."""
    xs, ys = [], []
    for sk in skulls:
        x0, x1, y0, y1 = sk.bbox()
        xs += [x0, x1]
        ys += [y0, y1]
        for lab in sk.s.get("labels", []):
            ax = draw.resolve(sk.s, lab["at"])[0]
            xs += list(label_extent(lab, ax))
            n = len(lab["text"].split("\n"))
            ys += [lab["to"][1] + 8, lab["to"][1] - 10.6 * (n - 1) - 5]
    # svg coords: x_svg = -x_mm, y_svg = -y_mm
    left, right = -max(xs) - 4, -min(xs) + 4
    top, bottom = -max(ys) - 3, -min(ys) + 21
    return (left, top, right - left, bottom - top)


def main(argv):
    preview = argv[argv.index("--preview") + 1] if "--preview" in argv else None
    ids = [i for i in ORDER if i in SKULLS]
    skulls = [draw.Skull(SKULLS[i]) for i in ids]
    vb = common_viewbox(skulls)
    # the strip icons use a tighter box without labels
    xs = [v for sk in skulls for v in sk.bbox()[:2]]
    ys = [v for sk in skulls for v in sk.bbox()[2:]]
    vb_icon = (-max(xs) - 3, -max(ys) - 3, max(xs) - min(xs) + 6, max(ys) - min(ys) + 6)
    out, areas = {}, {}
    for sid in ids:
        spec = SKULLS[sid]
        svg, sk = draw.render(spec, vb, f"Lateral skull diagram, {spec['specimen']}")
        out[sid] = dict(svg=svg, icon=draw.icon(spec, vb_icon), spec=spec["specimen"])
        areas[sid] = sk.endo_area
        if preview:
            os.makedirs(preview, exist_ok=True)
            with open(os.path.join(preview, f"{sid}.svg"), "w") as f:
                f.write(svg)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("/* generated by tools/build_diagrams.py from tools/diagrams/skulls.py */\n")
        f.write("window.SKULL_DIAGRAMS = ")
        json.dump(out, f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB), viewBox {tuple(round(v, 1) for v in vb)}")
    # brain-space check: 2-D area should scale roughly with volume^(2/3)
    for sid in ids:
        cc = SPECIMEN_CC.get(sid)
        k = areas[sid] / cc ** (2 / 3) if cc else float("nan")
        print(f"  {sid:8s} endocast area {areas[sid]:7.0f} mm2   specimen {cc or '-':>5} cc   area/cc^(2/3) {k:5.1f}")


if __name__ == "__main__":
    main(sys.argv[1:])
